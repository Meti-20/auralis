/**
 * Escapes a single CSV value according to RFC 4180:
 * Encloses value in double quotes if it contains commas, double quotes, or newlines.
 * Escapes internal quotes by doubling them ("").
 */
export function escapeCSVValue(val: string | number | boolean | null | undefined): string {
  if (val === null || val === undefined) return '""';
  const str = String(val);
  if (str.includes(',') || str.includes('"') || str.includes('\n') || str.includes('\r')) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return `"${str}"`;
}

/**
 * Initiates a browser client-side download for a Blob
 */
export function triggerFileDownload(content: string, filename: string, mimeType: string): boolean {
  if (typeof window === 'undefined') return false;

  try {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    link.style.display = 'none';
    document.body.appendChild(link);
    link.click();
    setTimeout(() => {
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    }, 200);
    return true;
  } catch (error) {
    console.error('File download failed:', error);
    return false;
  }
}

/**
 * Exports an array of transactions to a CSV file.
 */
export function exportTransactionsToCSV(
  transactions: DashboardTransaction[],
  currencySymbol = '$',
  companyName = 'Acme Technologies Inc.'
): { success: boolean; count: number; filename: string } {
  const dateStr = new Date().toISOString().split('T')[0];
  const filename = `auralis-transactions-${dateStr}.csv`;

  // UTF-8 BOM for Microsoft Excel compatibility
  const BOM = '\uFEFF';

  const headers = [
    'Transaction ID',
    'Transaction Name',
    'Category',
    'Type',
    'Date',
    'Amount',
    'Currency',
    'Status',
    'Account Reference',
  ];

  const rows = transactions.map((tx) => [
    escapeCSVValue(tx.id),
    escapeCSVValue(tx.name),
    escapeCSVValue(tx.category),
    escapeCSVValue(tx.type.toUpperCase()),
    escapeCSVValue(tx.date),
    escapeCSVValue(tx.amount.toFixed(2)),
    escapeCSVValue(currencySymbol),
    escapeCSVValue(tx.status),
    escapeCSVValue(tx.account),
  ]);

  const csvContent =
    BOM +
    `# AURALIS FINANCIAL WORKSPACE - TRANSACTION EXPORT\n` +
    `# Organization: ${companyName}\n` +
    `# Export Date: ${new Date().toLocaleString()}\n` +
    `# Total Items: ${transactions.length}\n\n` +
    headers.map(escapeCSVValue).join(',') +
    '\n' +
    rows.map((r) => r.join(',')).join('\n');

  const success = triggerFileDownload(csvContent, filename, 'text/csv;charset=utf-8;');
  return { success, count: transactions.length, filename };
}

/**
 * Generates an executive financial statement report in CSV format
 */
export function exportFinancialStatementCSV(params: {
  reportType: 'cashflow' | 'expenses' | 'tax';
  dateRange: DateRange;
  kpis: SummaryKPIs;
  categories: ExpenseCategoryItem[];
  transactions: DashboardTransaction[];
  profile: UserProfile;
  preferences: UserPreferences;
}): { success: boolean; filename: string } {
  const { reportType, dateRange, kpis, categories, transactions, profile, preferences } = params;
  const dateStr = new Date().toISOString().split('T')[0];
  const reportTitles: Record<string, string> = {
    cashflow: 'Cash Flow & Inflow Statement',
    expenses: 'Departmental Expense Breakdown',
    tax: 'Tax & Compliance Preparation Ledger',
  };

  const title = reportTitles[reportType] || 'Financial Report';
  const filename = `auralis-${reportType}-report-${dateRange}-${dateStr}.csv`;
  const BOM = '\uFEFF';

  let sections = '';

  // 1. Header Information
  sections += `# AURALIS FINANCIAL MANAGEMENT REPORT\n`;
  sections += `# Title: ${title}\n`;
  sections += `# Organization: ${profile.companyName}\n`;
  sections += `# Generated By: ${profile.fullName} (${profile.email})\n`;
  sections += `# Reporting Period: ${dateRange.toUpperCase()} (Generated on ${new Date().toLocaleDateString()})\n`;
  sections += `# Reporting Currency: ${preferences.currency} (${preferences.currencySymbol})\n\n`;

  // 2. Executive KPI Summary Section
  sections += `### EXECUTIVE KPI SUMMARY\n`;
  sections += `Metric,Amount (${preferences.currencySymbol}),Period Comparison,Trend\n`;
  sections += `Total Income,${kpis.totalIncome.amount.toFixed(2)},${kpis.totalIncome.comparisonLabel},+${kpis.totalIncome.changePercent}%\n`;
  sections += `Total Expenses,${kpis.totalExpenses.amount.toFixed(2)},${kpis.totalExpenses.comparisonLabel},${kpis.totalExpenses.changePercent}%\n`;
  sections += `Net Cash Flow (Surplus),${kpis.netCashFlow.amount.toFixed(2)},${kpis.netCashFlow.comparisonLabel},+${kpis.netCashFlow.changePercent}%\n`;
  sections += `Available Cash Balance,${kpis.availableBalance.amount.toFixed(2)},${kpis.availableBalance.comparisonLabel},+${kpis.availableBalance.changePercent}%\n\n`;

  // 3. Departmental Expense Breakdown Section
  if (reportType === 'expenses' || reportType === 'cashflow') {
    sections += `### DEPARTMENTAL EXPENSE ALLOCATION\n`;
    sections += `Department Category,Disbursed Amount (${preferences.currencySymbol}),Share of Total Expenses,Variance\n`;
    categories.forEach((cat) => {
      sections += `${cat.name},${cat.amount.toFixed(2)},${cat.percentage}%,${cat.changePercent >= 0 ? '+' : ''}${cat.changePercent}%\n`;
    });
    sections += '\n';
  }

  // 4. Ledger Item Details
  sections += `### ITEMIZED LEDGER RECORDS\n`;
  sections += `ID,Name,Category,Type,Date,Amount (${preferences.currencySymbol}),Status,Account\n`;

  const relevantTx =
    reportType === 'expenses'
      ? transactions.filter((t) => t.type === 'expense')
      : reportType === 'tax'
      ? transactions.filter((t) => t.status === 'Cleared')
      : transactions;

  relevantTx.forEach((tx) => {
    sections += `${escapeCSVValue(tx.id)},${escapeCSVValue(tx.name)},${escapeCSVValue(tx.category)},${escapeCSVValue(tx.type)},${escapeCSVValue(tx.date)},${tx.amount.toFixed(2)},${escapeCSVValue(tx.status)},${escapeCSVValue(tx.account)}\n`;
  });

  const success = triggerFileDownload(BOM + sections, filename, 'text/csv;charset=utf-8;');
  return { success, filename };
}

